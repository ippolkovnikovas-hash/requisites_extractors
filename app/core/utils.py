"""
Общие нормализаторы значений реквизитов.

Разделение на две функции намеренное и следует правилам из CLAUDE.md:

- `strip_formatting()` снимает только форматирование — пробелы (включая
  неразрывные), переносы, табуляции и тире. Символы при этом не подменяются:
  запись приводится к канонической форме, а не «исправляется».

- `fold_numeric_confusables()` дополнительно сворачивает узкий список
  однозначных OCR-подмен (`О`→`0`, `I`→`1` и т.п.) и отдельно сообщает, была ли
  подмена применена. Флаг нужен, чтобы валидатор мог показать пользователю
  предупреждение: значение изменилось не только форматированием.

Фолдинг применим только к полям, состоящим из одних цифр (ИНН, ОГРН, БИК,
счета). Для КПП его использовать нельзя — латинские буквы в 5-6 позиции там
легальны, и `O`/`I` в них подменять нечем.

Ни одна из функций не изменяет `raw_value`: результат кладётся в
`normalized_value`, исходное значение всегда сохраняется как есть.
"""

# Тире всех видов: обычный дефис, неразрывный дефис, en/em dash, минус.
_DASHES = frozenset("-‐‑‒–—―−")

# Узкий список однозначных OCR-подмен для чисто цифровых полей.
# Расширять его следует осторожно: каждая новая пара должна быть однозначной
# в контексте поля, где не бывает букв.
_NUMERIC_CONFUSABLES = {
    "O": "0",  # латинская O
    "o": "0",
    "О": "0",  # кириллическая О (U+041E)
    "о": "0",  # кириллическая о (U+043E)
    "I": "1",  # латинская I
    "l": "1",  # строчная латинская l
    "|": "1",  # вертикальная черта
    "І": "1",  # кириллическая І (U+0406)
    "і": "1",  # кириллическая і (U+0456)
}


def strip_formatting(value: str | None) -> str | None:
    """
    Убирает форматирование: любые пробельные символы и тире.

    `None` возвращается как `None`, пустая строка — как пустая строка:
    «значения нет» и «значение пустое» различаются на уровне вызывающего кода.
    """
    if value is None:
        return None
    return "".join(ch for ch in value if not ch.isspace() and ch not in _DASHES)


def collapse_whitespace(value: str | None) -> str | None:
    """
    Схлопывает любые последовательности пробельных символов (включая переносы
    строк) в один пробел и обрезает края.

    Для текстовых полей — наименований, адресов, ФИО — это единственная
    допустимая нормализация: порядок слов и сами слова не меняются.
    """
    if value is None:
        return None
    return " ".join(value.split())


def fold_numeric_confusables(value: str | None) -> tuple[str | None, bool]:
    """
    Снимает форматирование и сворачивает однозначные OCR-подмены.

    Возвращает `(нормализованное_значение, была_ли_подмена)`.

    Флаг `False`, если изменилось только форматирование: убранные пробелы и
    дефисы подменой символов не считаются. Символы вне списка подмен остаются
    как есть — функция ничего не удаляет и не «чинит» сверх списка, чтобы
    мусор дошёл до валидатора и стал видимой ошибкой, а не тихо исчез.
    """
    if value is None:
        return None, False

    stripped = strip_formatting(value)
    folded = "".join(_NUMERIC_CONFUSABLES.get(ch, ch) for ch in stripped)
    return folded, folded != stripped
